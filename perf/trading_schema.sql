-- Trading-style test schema (synthetic, Calypso-like in shape only). Run as the schema owner.
-- Integrity lives in the "application": only three foreign keys are declared (one a self reference, TRADE.PARENT_TRADE_ID),
-- the rest are references by name,
-- a type + ID pair (BO_MESSAGE), a shared-key extension table (PRODUCT_BOND) and keywords keyed by trade.
WHENEVER SQLERROR EXIT FAILURE

CREATE TABLE LEGAL_ENTITY (
  LE_ID          NUMBER(10)    NOT NULL,
  SHORT_NAME     VARCHAR2(32)  NOT NULL,
  FULL_NAME      VARCHAR2(128),
  COUNTRY        VARCHAR2(3),
  LEI            VARCHAR2(20),
  CONSTRAINT PK_LEGAL_ENTITY PRIMARY KEY (LE_ID),
  CONSTRAINT UQ_LE_SHORT UNIQUE (SHORT_NAME)
);

CREATE TABLE BOOK (
  BOOK_ID        NUMBER(10)    NOT NULL,
  BOOK_NAME      VARCHAR2(32)  NOT NULL,
  LE_ID          NUMBER(10)    NOT NULL,           -- undeclared reference to LEGAL_ENTITY
  BASE_CCY       VARCHAR2(3)   NOT NULL,
  ACTIVE_FLAG    NUMBER(1)     DEFAULT 1 NOT NULL,
  CONSTRAINT PK_BOOK PRIMARY KEY (BOOK_ID),
  CONSTRAINT UQ_BOOK_NAME UNIQUE (BOOK_NAME)
);

CREATE TABLE PRODUCT_DESC (
  PRODUCT_ID     NUMBER(12)    NOT NULL,
  PRODUCT_TYPE   VARCHAR2(32)  NOT NULL,
  DESCRIPTION    VARCHAR2(255),
  CURRENCY       VARCHAR2(3),
  MATURITY_DATE  DATE,
  CONSTRAINT PK_PRODUCT_DESC PRIMARY KEY (PRODUCT_ID)
);

-- 1:1 extension of PRODUCT_DESC sharing its key, no FK declared
CREATE TABLE PRODUCT_BOND (
  PRODUCT_ID     NUMBER(12)    NOT NULL,
  ISSUER_LE_ID   NUMBER(10),                       -- role-prefixed reference to LEGAL_ENTITY
  COUPON         NUMBER(9,6),
  FACE_VALUE     NUMBER(18,2),
  CONSTRAINT PK_PRODUCT_BOND PRIMARY KEY (PRODUCT_ID)
);

CREATE TABLE TRADE (
  TRADE_ID       NUMBER(12)    NOT NULL,
  EXTERNAL_REF   VARCHAR2(40)  NOT NULL,
  BOOK_ID        NUMBER(10)    NOT NULL,           -- undeclared
  CPTY_ID        NUMBER(10)    NOT NULL,           -- undeclared, name matches no table
  PRODUCT_ID     NUMBER(12)    NOT NULL,           -- undeclared
  TRADE_DATE     DATE          NOT NULL,
  SETTLE_DATE    DATE,
  QUANTITY       NUMBER(18,2)  NOT NULL,
  PRICE          NUMBER(18,8),
  NOTIONAL       NUMBER(20,2),
  CURRENCY       VARCHAR2(3)   NOT NULL,
  TRADE_STATUS   VARCHAR2(16)  NOT NULL,
  VERSION_NUM    NUMBER(6)     DEFAULT 0 NOT NULL,
  ENTERED_TIME   TIMESTAMP(6)  NOT NULL,
  PARENT_TRADE_ID NUMBER(12),                      -- amended/novated from: a declared self reference
  CONSTRAINT PK_TRADE PRIMARY KEY (TRADE_ID),
  CONSTRAINT UQ_TRADE_EXT UNIQUE (EXTERNAL_REF),
  CONSTRAINT FK_TRADE_PARENT FOREIGN KEY (PARENT_TRADE_ID) REFERENCES TRADE (TRADE_ID)
);
CREATE INDEX IX_TRADE_BOOK ON TRADE (BOOK_ID, TRADE_DATE);

CREATE TABLE TRADE_KEYWORD (
  TRADE_ID       NUMBER(12)    NOT NULL,           -- undeclared
  KEYWORD_NAME   VARCHAR2(32)  NOT NULL,
  KEYWORD_VALUE  VARCHAR2(255),
  CONSTRAINT PK_TRADE_KEYWORD PRIMARY KEY (TRADE_ID, KEYWORD_NAME)
);

-- type + ID pair: OBJECT_ID points at a different table depending on OBJECT_CLASS
CREATE TABLE BO_MESSAGE (
  MESSAGE_ID     NUMBER(12)    NOT NULL,
  OBJECT_ID      NUMBER(12)    NOT NULL,
  OBJECT_CLASS   VARCHAR2(32)  NOT NULL,
  MESSAGE_TYPE   VARCHAR2(32)  NOT NULL,
  MSG_STATUS     VARCHAR2(16)  NOT NULL,
  CREATED_TIME   TIMESTAMP(6)  NOT NULL,
  CONSTRAINT PK_BO_MESSAGE PRIMARY KEY (MESSAGE_ID)
);

-- the two declared foreign keys
CREATE TABLE TRADE_FEE (
  FEE_ID         NUMBER(12)    NOT NULL,
  TRADE_ID       NUMBER(12)    NOT NULL,
  FEE_TYPE       VARCHAR2(16)  NOT NULL,
  AMOUNT         NUMBER(18,2)  NOT NULL,
  CONSTRAINT PK_TRADE_FEE PRIMARY KEY (FEE_ID),
  CONSTRAINT FK_FEE_TRADE FOREIGN KEY (TRADE_ID) REFERENCES TRADE (TRADE_ID)
);
CREATE TABLE BOOK_ATTRIBUTE (
  BOOK_ID        NUMBER(10)    NOT NULL,
  ATTR_NAME      VARCHAR2(32)  NOT NULL,
  ATTR_VALUE     VARCHAR2(128),
  CONSTRAINT PK_BOOK_ATTRIBUTE PRIMARY KEY (BOOK_ID, ATTR_NAME),
  CONSTRAINT FK_BOOKATTR_BOOK FOREIGN KEY (BOOK_ID) REFERENCES BOOK (BOOK_ID)
);

-- leftovers every real vendor schema has: backups and scratch tables
CREATE TABLE BKP_TRADE_2023 AS SELECT * FROM TRADE WHERE 1 = 0;
CREATE TABLE TMP_RECON_STAGE (RUN_ID NUMBER(10), TRADE_ID NUMBER(12), NOTE VARCHAR2(100));

CREATE SEQUENCE SEQ_TRADE START WITH 1 INCREMENT BY 1 CACHE 100;
CREATE SEQUENCE SEQ_BO_MESSAGE START WITH 1 INCREMENT BY 1 CACHE 100;

CREATE OR REPLACE VIEW V_TRADE_SUMMARY AS
  SELECT b.BOOK_NAME, t.CURRENCY, COUNT(*) AS TRADES, SUM(t.NOTIONAL) AS NOTIONAL
    FROM TRADE t JOIN BOOK b ON b.BOOK_ID = t.BOOK_ID
   WHERE t.TRADE_STATUS <> 'CANCELED'
   GROUP BY b.BOOK_NAME, t.CURRENCY;

CREATE OR REPLACE VIEW V_OPEN_MESSAGES AS
  SELECT MESSAGE_ID, OBJECT_ID, MESSAGE_TYPE FROM BO_MESSAGE WHERE MSG_STATUS = 'PENDING';

CREATE OR REPLACE PACKAGE PKG_TRADE_UTIL AS
  FUNCTION trade_notional(p_trade_id IN NUMBER) RETURN NUMBER;
  PROCEDURE cancel_trade(p_trade_id IN NUMBER);
END PKG_TRADE_UTIL;
/

CREATE OR REPLACE PACKAGE BODY PKG_TRADE_UTIL AS
  FUNCTION trade_notional(p_trade_id IN NUMBER) RETURN NUMBER IS
    v NUMBER;
  BEGIN
    SELECT NOTIONAL INTO v FROM TRADE WHERE TRADE_ID = p_trade_id;
    RETURN v;
  END trade_notional;

  PROCEDURE cancel_trade(p_trade_id IN NUMBER) IS
  BEGIN
    UPDATE TRADE SET TRADE_STATUS = 'CANCELED', VERSION_NUM = VERSION_NUM + 1 WHERE TRADE_ID = p_trade_id;
  END cancel_trade;
END PKG_TRADE_UTIL;
/

CREATE OR REPLACE FUNCTION FN_BOOK_LE(p_book_id IN NUMBER) RETURN NUMBER IS
  v NUMBER;
BEGIN
  SELECT LE_ID INTO v FROM BOOK WHERE BOOK_ID = p_book_id;
  RETURN v;
END FN_BOOK_LE;
/

